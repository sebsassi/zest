/**
    @brief Alias for a `TensorShape` with only dynamic extents.

    @tparam rank Rank of the `TensorShape`.
*/
template <std::size_t rank>
using DynamicTensorShape
    = detail::DynamicTensorShapeHelper<std::make_index_sequence<rank>>::type;

template <std::size_t... extent_params>
    requires ((extent_params != std::dynamic_extent) && ...)
class TensorShape<extent_params...>
{
public:
    using size_type = std::size_t;
    using index_type = size_type;
    using index_range = StandardIndexRange<size_type>;
    using extent_type = std::array<size_type, sizeof...(extent_params)>;
    using dynamic_extent_type = std::array<size_type, 0>;

    static constexpr size_type rank = sizeof...(extent_params);
    static constexpr std::size_t linear_extent = product(std::array{extent_params...});
    static constexpr extent_type static_extents = std::array{extent_params...};

private:
    template <std::size_t N, typename T>
    struct subshape_helper;

    template <std::size_t N, std::size_t... Inds>
        requires (sizeof...(Inds) == rank - N && 1 <= N && N < rank)
    struct subshape_helper<N, std::index_sequence<Inds...>>
    {
        using type = TensorShape<std::get<N + Inds>(static_extents)...>;
    };

    template <std::size_t N>
        requires (N == rank)
    struct subshape_helper<N, std::index_sequence<>>
    {
        using type = NullShape;
    };

public:
    template <std::size_t N>
        requires (0 < N && N <= rank)
    using subshape_type = subshape_helper<N, std::make_index_sequence<rank - N>>::type;

    constexpr TensorShape() = default;
    explicit constexpr TensorShape([[maybe_unused]] const extent_type& extents) {}
    explicit constexpr TensorShape(
        [[maybe_unused]] const dynamic_extent_type& dynamic_extents) {}

    template <std::integral... ExtentTypes>
        requires (sizeof...(ExtentTypes) == rank)
    explicit constexpr TensorShape([[maybe_unused]] ExtentTypes... extents) {}

    [[nodiscard]] static constexpr size_type
    size([[maybe_unused]] const extent_type& extents) noexcept
    {
        return linear_extent;
    }

    [[nodiscard]] static constexpr size_type
    size([[maybe_unused]] const dynamic_extent_type& dynamic_extents) noexcept
    {
        return linear_extent;
    }

    [[nodiscard]] static constexpr size_type
    size() noexcept { return linear_extent; }

    [[nodiscard]] constexpr dynamic_extent_type
    dynamic_extents() const noexcept { return {}; }

    [[nodiscard]] constexpr extent_type
    extents() const noexcept { return static_extents; }

    [[nodiscard]] constexpr size_type
    extent(size_type i) const noexcept { return static_extents[i]; }

    template <std::size_t I>
        requires (I < rank)
    [[nodiscard]] constexpr size_type
    extent() const noexcept
    {
        return static_extents[I];
    }

    template <std::integral... Inds>
        requires (1 <= sizeof...(Inds) && sizeof...(Inds) < rank)
    [[nodiscard]] constexpr auto
    subshape([[maybe_unused]] Inds... inds) const noexcept
    {
        return subshape_type<sizeof...(Inds)>{};
    }

    template <std::integral... Inds>
        requires (sizeof...(Inds) == rank)
    [[nodiscard]] constexpr auto
    subshape([[maybe_unused]] Inds... inds) const noexcept { return NullShape{}; }

    template <std::integral... Inds>
        requires (1 <= sizeof...(Inds) && sizeof...(Inds) <= rank)
    [[nodiscard]] constexpr index_type
    operator()(Inds... indices) const noexcept
    {
        return array::detail::index(static_extents, index_type(indices)...);
    }

    [[nodiscard]] constexpr auto
    indices() const noexcept { return index_range{index_type{static_extents[0]}}; }

    [[nodiscard]] constexpr auto
    indices(index_type index) const noexcept
    {
        return index_range{index, index_type{static_extents[0]}};
    }
};

/**
    @brief Compose an outer shape and an inner shape to a new shape.

    @tparam OuterShape
    @tparam InnerShape
*/
template <typename OuterShape, typename InnerShape>
class CompositeShape
{
public:
    using first_component_type = OuterShape;
    using second_component_type = InnerShape;
    using size_type = typename OuterShape::size_type;
    using index_type = typename OuterShape::index_type;
    using index_range = typename OuterShape::index_range;
    using extent_type
        = std::tuple<typename OuterShape::extent_type, typename InnerShape::extent_type>;

    static constexpr size_type rank = OuterShape::rank + InnerShape::rank;
    static constexpr std::size_t linear_extent
        = (OuterShape::linear_extent == std::dynamic_extent
                || InnerShape::linear_extent == std::dynamic_extent) ?
            std::dynamic_extent : OuterShape::linear_extent*InnerShape::linear_extent;
private:
    template <std::size_t N>
    struct subshape_helper;

    template <std::size_t N>
        requires (N < OuterShape::rank)
    struct subshape_helper<N>
    {
        using type
            = CompositeShape<typename OuterShape::template subshape_type<N>, InnerShape>;
    };

    template <std::size_t N>
        requires (N == OuterShape::rank)
    struct subshape_helper<N>
    {
        using type = InnerShape;
    };

    template <std::size_t N>
        requires (OuterShape::rank < N && N < rank)
    struct subshape_helper<N>
    {
        using type = typename InnerShape::template subshape_type<N - OuterShape::rank>;
    };

    template <std::size_t N>
        requires (N == rank)
    struct subshape_helper<N>
    {
        using type = NullShape;
    };

public:
    /**
        @brief Subshapes of the shape.
    */
    template <std::size_t N>
        requires (N > 0)
    using subshape_type = subshape_helper<N>::type;

    constexpr CompositeShape() = default;

    /**
        @brief Construct a composite shape from the extents of its inner and
        outer shapes.

        @param outer_extents Extents of the outer shape.
        @param inner_extents Extents of the inner shape.
    */
    template <typename E1, typename E2>
        requires std::constructible_from<OuterShape, E1>
            && std::constructible_from<InnerShape, E2>
    constexpr CompositeShape(const E1& outer_extents, const E2& inner_extents):
        m_shapes{OuterShape{outer_extents}, InnerShape{inner_extents}} {}

    /**
        @brief Construct a composite shape with inner static extents from the
        extents of its outer shape.

        @param outer_extents Extents of the outer shape.
    */
    template <typename E>
        requires std::constructible_from<OuterShape, E>
    explicit constexpr CompositeShape(const E& outer_extents)
        requires (OuterShape::linear_extent == std::dynamic_extent
            && InnerShape::linear_extent != std::dynamic_extent):
        m_shapes{OuterShape{outer_extents}, InnerShape{}} {}

    /**
        @brief Construct a composite shape with outer static extents from the
        extents of its inner shape.

        @param inner_extents Extents of the inner shape.
    */
    template <typename E>
        requires std::constructible_from<InnerShape, E>
    explicit constexpr CompositeShape(const E& inner_extents)
        requires (OuterShape::linear_extent != std::dynamic_extent
            && InnerShape::linear_extent == std::dynamic_extent):
        m_shapes{OuterShape{}, InnerShape{inner_extents}} {}

    /**
        @brief Construct a composite shape from its component shapes.
    */
    constexpr CompositeShape(const OuterShape& outer_shape, const InnerShape& inner_shape):
        m_shapes(outer_shape, inner_shape) {}

    /**
        @brief Size of a composite shape given the outer and inner extents.

        @param outer_extents Extents of the outer shape.
        @param inner_extents Extents of the inner shape.
    */
    [[nodiscard]] static constexpr size_type
    size(
        const OuterShape::extent_type& outer_extents,
        const InnerShape::extent_type& inner_extents) noexcept
    {
        return OuterShape::size(outer_extents)*InnerShape::size(inner_extents);
    }

    /**
        @brief Size of a composite shape with inner static extents given the
        extents of its outer shape.

        @param outer_extents Extents of the outer shape.
    */
    [[nodiscard]] static constexpr size_type
    size(const OuterShape::extent_type& outer_extents)
        requires (OuterShape::linear_extent == std::dynamic_extent
            && InnerShape::linear_extent != std::dynamic_extent)
    {
        return OuterShape::size(outer_extents)*InnerShape::linear_extent;
    }

    /**
        @brief Size of a composite shape with outer static extents given the
        extents of its inner shape.

        @param inner_extents Extents of the inner shape.
    */
    [[nodiscard]] static constexpr size_type
    size(const InnerShape::extent_type& inner_extents)
        requires (OuterShape::linear_extent != std::dynamic_extent
            && InnerShape::linear_extent == std::dynamic_extent)
    {
        return OuterShape::linear_extent*InnerShape::size(inner_extents);
    }

    /**
        @brief Size of the shape.
    */
    [[nodiscard]] static constexpr size_type
    size() noexcept requires (linear_extent != std::dynamic_extent) { return linear_extent; }

    [[nodiscard]] constexpr size_type
    size() const noexcept requires (linear_extent == std::dynamic_extent)
    {
        return m_shapes.first.size()*m_shapes.second.size();
    }

    /**
        @brief Order paramter of the shape if the outer shape is a sequenced
        shape.
    */
    [[nodiscard]] constexpr OuterShape::extent_type
    order() const noexcept requires sequence_shaped<OuterShape>
    {
        return m_shapes.first.extents();
    }

    /**
        @brief Extent of the shape at a given index.
    */
    [[nodiscard]] constexpr size_type
    extent(size_type index) const noexcept { return m_shapes.first.extent(index); }

    /**
        @brief Extents of the shape.
    */
    [[nodiscard]] constexpr extent_type
    extents() const noexcept
    {
        return {m_shapes.first.extents(), m_shapes.second.extents()};
    }

    template <std::integral... Inds>
        requires (1 <= sizeof...(Inds) && sizeof...(Inds) < OuterShape::rank)
    [[nodiscard]] constexpr auto
    subshape(Inds... indices) const noexcept
    {
        return subshape_type<sizeof...(Inds)>{
            m_shapes.first.subshape((typename OuterShape::index_type)(indices)...),
            m_shapes.second
        };
    }

    /**
        @brief Subshape of the shape.

        @param indices Indices at which the subshape is taken.
    */
    template <std::integral... Inds>
        requires (sizeof...(Inds) == OuterShape::rank)
    [[nodiscard]] constexpr auto
    subshape([[maybe_unused]] Inds... indices) const noexcept
    {
        return subshape_type<sizeof...(Inds)>{m_shapes.second};
    }

    template <std::integral... Inds>
        requires (OuterShape::rank < sizeof...(Inds) && sizeof...(Inds) < rank)
    [[nodiscard]] constexpr auto
    subshape(Inds... indices) const noexcept
    {
        auto impl = [&]<std::size_t... I, typename T>(std::index_sequence<I...>, T index_tuple)
        {
            return subshape_type<sizeof...(Inds)>{
                m_shapes.second.subshape(std::get<OuterShape::rank + I>(index_tuple)...)
            };
        };
        return impl(
            std::make_index_sequence<sizeof...(Inds) - OuterShape::rank>{},
            std::make_tuple(indices...));
    }

    template <std::integral... Inds>
        requires (sizeof...(Inds) == rank)
    [[nodiscard]] constexpr auto
    subshape([[maybe_unused]] Inds... indices) const noexcept
    {
        return subshape_type<sizeof...(Inds)>(NullShape{});
    }

    /**
        @brief Get the contiguous index corresponding to the shape indices.

        @param indices Indices mapped to the contiquous sequence.
    */
    template <std::integral... Inds>
        requires (1 <= sizeof...(Inds) && sizeof...(Inds) <= rank)
    [[nodiscard]] constexpr index_type
    operator()(Inds... indices) const noexcept { return index(index_type(indices)...); }

    /**
        @brief Index range of the shape.
    */
    [[nodiscard]] constexpr index_range
    indices() const noexcept { return m_shapes.first.indices(); }

    /**
        @brief Index range of the shape starting at a given index.

        @brief index Starting index.
    */
    [[nodiscard]] constexpr index_range
    indices(index_type index) const noexcept { return m_shapes.first.indices(index); }

private:
    template <std::integral... Inds>
        requires (1 <= sizeof...(Inds) && sizeof...(Inds) <= OuterShape::rank)
    [[nodiscard]] constexpr index_type
    index(Inds... indices) const noexcept
    {
        using outer_index_type = typename OuterShape::index_type;
        return m_shapes.first(outer_index_type(indices)...)*m_shapes.second.size();
    }

    template <std::integral... Inds>
        requires (OuterShape::rank < sizeof...(Inds) && sizeof...(Inds) <= rank)
    [[nodiscard]] constexpr index_type
    index(Inds... indices) const noexcept
    {
        auto impl = [&]<std::size_t... I, std::size_t... J, typename T>
        (std::index_sequence<I...>, std::index_sequence<J...>, T index_tuple)
        {
            using outer_index_type = typename OuterShape::index_type;
            using inner_index_type = typename InnerShape::index_type;
            return m_shapes.first(
                    outer_index_type(std::get<I>(index_tuple))...)*m_shapes.second.size()
                + m_shapes.second(
                    inner_index_type(std::get<OuterShape::rank + J>(index_tuple))...);
        };
        return impl(
            std::make_index_sequence<OuterShape::rank>{},
            std::make_index_sequence<sizeof...(Inds) - OuterShape::rank>{},
            std::make_tuple(indices...));
    }

    std::pair<OuterShape, InnerShape> m_shapes{};
};

/**
    @brief Alias for a shape describing a sequenced shape of tensor shapes.

    @tparam SequenceType Type of the outer sequenced shape.
    @tparam extent_params Inner tensor shape extents.
*/
template <typename SequenceType, std::size_t... extent_params>
using TensorSequenceShape = std::conditional_t<(sizeof...(extent_params) > 0),
    CompositeShape<SequencedShape<SequenceType>, TensorShape<extent_params...>>,
    SequencedShape<SequenceType>>;

/**
    @brief Alias for a shape describing a tensor of sequenced shapes.

    @tparam SequenceType Type of the inner sequenced shape.
    @tparam extent_params Outer tensor shape extents.
*/
template <typename SequenceType, std::size_t... extent_params>
using SequenceTensorShape = std::conditional_t<(sizeof...(extent_params) > 0),
    CompositeShape<TensorShape<extent_params...>, SequencedShape<SequenceType>>,
    SequencedShape<SequenceType>>;

/**
    @brief Helper type for attaching arbitrary tag types to shapes.

    @tparam ShapeType Shape to be tagged.
    @tparam Tags Types tagging the shape type.
*/
template <typename ShapeType, tag_type... Tags>
struct TaggedShape: public ShapeType, public Tags...
{
    using untag = ShapeType;

    template <std::size_t N>
    using subshape_type = TaggedShape<typename ShapeType::template subshape_type<N>, Tags...>;

    using ShapeType::ShapeType;

    explicit TaggedShape(const ShapeType& other): ShapeType(other) {}
};

